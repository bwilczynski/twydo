// Generate src/gen/protocol.d.ts from the OpenRPC schema's components.schemas.
import { compile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const doc = JSON.parse(await readFile(resolve(root, "../schema/tdo.openrpc.json"), "utf8"));

const rewrite = (v) => {
  if (Array.isArray(v)) return v.map(rewrite);
  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v).map(([k, x]) =>
        k === "$ref" && typeof x === "string"
          ? [k, x.replace("#/components/schemas/", "#/definitions/")]
          : [k, rewrite(x)],
      ),
    );
  }
  return v;
};

const definitions = rewrite(doc.components.schemas);
const schema = {
  title: "Protocol",
  type: "object",
  properties: Object.fromEntries(
    Object.keys(definitions).map((k) => [k, { $ref: `#/definitions/${k}` }]),
  ),
  additionalProperties: false,
  definitions,
};
const ts = await compile(schema, "Protocol", {
  bannerComment: "/* Generated by scripts/gen-types.mjs from schema/tdo.openrpc.json. Do not edit. */",
  additionalProperties: false,
  unreachableDefinitions: true,
});
await mkdir(resolve(root, "src/gen"), { recursive: true });
await writeFile(resolve(root, "src/gen/protocol.d.ts"), ts);
