use std::path::{Path, PathBuf};

use twydo_core::config::{Config, SyncConfig};
use twydo_core::sync::vdirsyncer::{config_path, ensure, render};

fn sync() -> SyncConfig {
    SyncConfig {
        url: "https://dav.example.test/alice/".into(),
        username: "alice".into(),
        password_command: vec!["pass".into(), "show".into(), "twydo/caldav".into()],
        ..SyncConfig::default()
    }
}

#[test]
fn render_full_config_golden() {
    let got = render(Path::new("/v"), &sync(), Path::new("/s"), None);
    let want = r#"# Generated by Twydo from config.toml; do not edit, it is overwritten.
[general]
status_path = "/s/vdirsyncer/status/"

[pair twydo]
a = "twydo_remote"
b = "twydo_local"
collections = ["from a", "from b"]
metadata = ["displayname", "color"]
conflict_resolution = ["command", "tdo", "conflicts", "hook"]

[storage twydo_local]
type = "filesystem"
path = "/v/"
fileext = ".ics"

[storage twydo_remote]
type = "caldav"
url = "https://dav.example.test/alice/"
username = "alice"
password.fetch = ["command", "pass", "show", "twydo/caldav"]
"#;
    assert_eq!(got, want);
}

#[test]
fn render_with_ca_file_adds_verify() {
    let mut s = sync();
    s.ca_file = Some(PathBuf::from("/ca.pem"));
    let got = render(Path::new("/v"), &s, Path::new("/s"), None);
    assert!(got.contains("verify = \"/ca.pem\"\n"));
    assert!(got.find("[storage twydo_remote]").unwrap() < got.find("verify").unwrap());
}

#[test]
fn render_escapes_values() {
    let mut s = sync();
    s.username = "a\"b\\c".into();
    s.password_command = vec!["sh".into(), "-c".into(), "pass show 'x y'".into()];
    let got = render(Path::new("/v"), &s, Path::new("/s"), None);
    assert!(got.contains(r#"username = "a\"b\\c""#));
    assert!(got.contains(r#"password.fetch = ["command", "sh", "-c", "pass show 'x y'"]"#));
}

#[test]
fn render_test_remote_is_filesystem() {
    let got = render(
        Path::new("/v"),
        &sync(),
        Path::new("/s"),
        Some(Path::new("/srv")),
    );
    let remote = got.split("[storage twydo_remote]\n").nth(1).unwrap();
    assert_eq!(
        remote,
        "type = \"filesystem\"\npath = \"/srv/\"\nfileext = \".ics\"\n"
    );
}

#[test]
fn ensure_writes_once_and_marks_rediscover() {
    let d = tempfile::tempdir().unwrap();
    let vstate = d.path().join("vstate");
    let cfg: Config = toml::from_str("vdir = \"/v\"").unwrap();
    let marker = vstate.join("sync/rediscover");

    let path = ensure(&cfg, &sync(), &vstate).unwrap();
    assert_eq!(path, config_path(&vstate));
    assert!(path.is_file() && marker.is_file());

    std::fs::remove_file(&marker).unwrap();
    let before = std::fs::metadata(&path).unwrap().modified().unwrap();
    std::thread::sleep(std::time::Duration::from_millis(20));
    ensure(&cfg, &sync(), &vstate).unwrap();
    assert!(!marker.exists());
    assert_eq!(
        std::fs::metadata(&path).unwrap().modified().unwrap(),
        before
    );

    let mut changed = sync();
    changed.username = "bob".into();
    ensure(&cfg, &changed, &vstate).unwrap();
    assert!(marker.is_file());
    assert!(std::fs::read_to_string(&path).unwrap().contains("\"bob\""));
}
